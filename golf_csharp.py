"""Write the C# the Unity client reads its messages with.

The client used to quote field names as strings, which is how a rename on the
server became a hole that drew as nothing with no error anywhere. Generated
from the declaration in golf_protocol, those names become properties: rename
one and the C# that still uses the old name stops compiling.

That only holds while the generated file is current, which is why the test
suite regenerates it and compares. A stale generated file is the one way this
can go wrong, and it is a single total comparison rather than a list anybody
maintains.

Run it directly to rewrite the file:  python golf_csharp.py
"""

from pathlib import Path

from golf_protocol import MESSAGES, Message, Part

OUTPUT = Path(__file__).parent / "unity" / "Assets" / "Scripts" / "Net" / "Messages.g.cs"

HEADER = '''// <auto-generated>
//   Written by golf_csharp.py from the declaration in golf_protocol.py.
//   Do not edit: the test suite regenerates this and compares, so an edit here
//   fails the build rather than surviving it.
//
//   Every field the server sends is a property here. A field renamed on the
//   server changes this file, and any C# still using the old name stops
//   compiling - which is the entire reason this is generated rather than
//   typed. Nullable throughout, because a message carries what it carries and
//   a hole with no boundary really does send null.
// </auto-generated>

using System.Collections.Generic;
using Newtonsoft.Json;

namespace Golf.Net.Wire
{
'''


def _pascal(name):
    """message_field -> MessageField, which is what C# expects to read."""
    return "".join(word.capitalize() for word in name.split("_"))


def _class(name, about, fields, parts, indent="    "):
    lines = [f"{indent}/// <summary>{about}</summary>",
             f"{indent}public class {name}", f"{indent}{{"]
    for field in fields:
        if field.about:
            lines.append(f"{indent}    /// <summary>{field.about}</summary>")
        lines.append(f'{indent}    [JsonProperty("{field.name}")]')
        lines.append(
            f"{indent}    public {field.kind} {_pascal(field.name)} "
            "{ get; set; }")
        lines.append("")
    for part in parts:
        kind = f"List<{part.name}>" if part.repeated else part.name
        if part.about:
            lines.append(f"{indent}    /// <summary>{part.about}</summary>")
        lines.append(f'{indent}    [JsonProperty("{part.field}")]')
        lines.append(
            f"{indent}    public {kind} {_pascal(part.field)} {{ get; set; }}")
        lines.append("")
    if lines[-1] == "":
        lines.pop()
    lines.append(f"{indent}}}")
    return lines


def _gather_parts(message, into):
    """Every nested object used anywhere, declared once each."""
    for part in message.parts if isinstance(message, Message) else message.parts:
        if part.name not in into:
            into[part.name] = part
            _gather_parts(part, into)
    return into


def generate():
    """The whole file, as a string."""
    parts = {}
    for message in MESSAGES:
        _gather_parts(message, parts)

    lines = [HEADER.rstrip("\n")]
    lines.append("    // --- Pieces that appear inside messages ---")
    lines.append("")
    for part in parts.values():
        lines += _class(part.name, part.about, part.fields, part.parts)
        lines.append("")

    lines.append("    // --- The messages themselves ---")
    lines.append("")
    for message in MESSAGES:
        name = _pascal(message.kind.lower()) + "Message"
        lines += _class(name, message.about, message.fields, message.parts)
        lines.append("")

    lines.append("    /// <summary>The name each message goes by on the wire.")
    lines.append("    /// Dispatch on these rather than on a typed string.</summary>")
    lines.append("    public static class Wire")
    lines.append("    {")
    for message in MESSAGES:
        lines.append(f'        public const string {_pascal(message.kind.lower())} '
                     f'= "{message.kind}";')
    lines.append("    }")
    lines.append("}")
    return "\n".join(lines) + "\n"


def write():
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(generate(), encoding="utf-8")
    return OUTPUT


if __name__ == "__main__":
    written = write()
    print(f"wrote {written} ({len(generate().splitlines())} lines)")
